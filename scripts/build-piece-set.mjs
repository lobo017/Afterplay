// Builds src/render/classic-pieces.ts: the "Classic" piece set.
//
//   node scripts/build-piece-set.mjs
//
// The pieces are Colin M.L. Burnett's SVG chess pieces (the set Wikipedia and Lichess show by default), licensed
// GPL-2.0-or-later (also GFDL and BSD); see LICENSES/README.md. They are fetched once, at dev time, from the Lichess
// repository at a pinned commit, and committed as a generated module: the app itself never downloads anything.
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'render', 'classic-pieces.ts');
/** lichess-org/lila, the last commit that touched public/piece/cburnett (2026-09-26). */
const COMMIT = '5b44d719ec5913dd62aa965f4b8d21e60a00c2c1';
const BASE = `https://raw.githubusercontent.com/lichess-org/lila/${COMMIT}/public/piece/cburnett`;
const COLORS = ['w', 'b'];
const PIECES = ['p', 'n', 'b', 'r', 'q', 'k'];
const TIMEOUT_MS = 30_000;

async function fetchText(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(TIMEOUT_MS) });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

/** The drawing inside the <svg> element, and its viewBox. */
function innerSvg(name, text) {
  const match = /^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(text);
  if (!match) throw new Error(`${name}: not a single <svg> element`);
  const viewBox = /\bviewBox="([^"]+)"/.exec(match[1])?.[1];
  if (viewBox !== '0 0 45 45') throw new Error(`${name}: unexpected viewBox ${viewBox}`);
  const inner = match[2].trim();
  // Markup that could collide between pieces on one page, or run anything, has no place in a piece
  if (/<script|\bon[a-z]+=|\bid="|href=|url\(/i.test(inner)) throw new Error(`${name}: unexpected markup`);
  if (inner.includes("'") || inner.includes('`') || inner.includes('\\'))
    throw new Error(`${name}: unexpected character`);
  return inner;
}

const sets = {};
for (const color of COLORS) {
  sets[color] = {};
  for (const piece of PIECES) {
    const name = `${color}${piece.toUpperCase()}.svg`;
    sets[color][piece] = innerSvg(name, await fetchText(`${BASE}/${name}`));
    console.log(`${name}: ${sets[color][piece].length} characters`);
  }
}

const entries = (color) => PIECES.map((piece) => `    ${piece}: '${sets[color][piece]}',`).join('\n');
const source = `// Generated by scripts/build-piece-set.mjs: do not edit by hand.
//
// The "Classic" piece set: Colin M.L. Burnett's SVG chess pieces, GPL-2.0-or-later (see LICENSES/README.md),
// from lichess-org/lila public/piece/cburnett at commit ${COMMIT.slice(0, 12)}.
import type { Color, PieceSymbol } from '../core/rules';

export const CLASSIC_PIECE_VIEWBOX = '0 0 45 45';

/** The drawing of each piece (what goes inside its <svg> element). */
export const CLASSIC_PIECES: Readonly<Record<Color, Readonly<Record<PieceSymbol, string>>>> = {
  w: {
${entries('w')}
  },
  b: {
${entries('b')}
  },
};
`;

const options = (await prettier.resolveConfig(OUT)) ?? {};
fs.writeFileSync(OUT, await prettier.format(source, { ...options, filepath: OUT }));
console.log(`wrote ${path.relative(ROOT, OUT)}`);
process.exit(0);
