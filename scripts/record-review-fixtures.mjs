// Records Stockfish results for the review classification fixtures.
//
//   npm run fixtures:review
//
// Reads tests/fixtures/review/classification-fixtures.json and writes
// tests/fixtures/review/classification-evals.json. For each fixture line it analyzes the
// last three positions (before the opponent's previous move, before the move under test,
// after it) with the single-threaded Stockfish build at a fixed depth, MultiPV 2, after
// `ucinewgame`. Single thread + fixed depth + cleared hash makes the output reproducible,
// so the unit tests can classify from these numbers without running an engine.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { createNodeStockfishTransport } from './lib/node-stockfish.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const fixturesPath = path.join(rootDir, 'tests/fixtures/review/classification-fixtures.json');
const outPath = path.join(rootDir, 'tests/fixtures/review/classification-evals.json');

const RECORD_DEPTH = Number(process.env.REVIEW_FIXTURE_DEPTH ?? 18);
const MULTIPV = 2;
const HASH_MB = 32;
const PV_PLIES = 12;

async function main() {
  const spec = JSON.parse(fs.readFileSync(fixturesPath, 'utf8'));
  const vite = await createServer({
    root: rootDir,
    logLevel: 'error',
    server: { middlewareMode: true, hmr: false },
    appType: 'custom',
  });
  const { RulesAdapter } = await vite.ssrLoadModule('/src/core/rules.ts');
  const { EngineClient } = await vite.ssrLoadModule('/src/engine/engine-client.ts');

  const engine = new EngineClient({
    variant: 'single-threaded',
    hashMb: HASH_MB,
    transportFactory: () => createNodeStockfishTransport(),
  });
  await engine.init();

  const out = {
    description:
      'Generated by scripts/record-review-fixtures.mjs. Do not edit by hand. Scores are from the side to move.',
    engine: engine.getEngineName(),
    depth: RECORD_DEPTH,
    multipv: MULTIPV,
    hashMb: HASH_MB,
    lines: {},
  };

  const startedAt = performance.now();
  try {
    for (const fixture of spec.fixtures) {
      const startFen = spec.positions[fixture.startFen] ?? fixture.startFen;
      const adapter = new RulesAdapter(startFen);
      const fens = [adapter.fen()];
      for (const uci of fixture.moves) {
        adapter.move(uci);
        fens.push(adapter.fen());
      }

      const firstIndex = Math.max(0, fixture.moves.length - 2);
      const positions = [];
      let first = true;
      for (let i = firstIndex; i <= fixture.moves.length; i++) {
        const probe = new RulesAdapter(startFen);
        for (const uci of fixture.moves.slice(0, i)) probe.move(uci);
        const record = { ply: i, fen: fens[i] };
        if (probe.isCheckmate()) record.terminal = 'checkmate';
        else if (probe.isStalemate()) record.terminal = 'stalemate';
        else if (probe.isInsufficientMaterial()) record.terminal = 'insufficient';

        if (!record.terminal) {
          const res = await engine.analyze({
            fen: startFen,
            moves: fixture.moves.slice(0, i),
            depth: RECORD_DEPTH,
            multipv: MULTIPV,
            useCache: false,
            resetGame: first,
            priority: 'live',
          });
          first = false;
          record.depth = res.depth;
          record.nodes = res.nodes;
          record.lines = res.lines.map((line) => ({
            multipv: line.multipv,
            score: line.score,
            pv: line.pv.slice(0, PV_PLIES),
          }));
        } else {
          record.depth = 0;
          record.lines = [];
        }
        positions.push(record);
      }

      out.lines[fixture.id] = {
        // Lets the tests notice a fixture that changed after recording
        key: `${startFen}|${fixture.moves.join(' ')}`,
        positions,
      };
      const last = positions[positions.length - 2];
      console.log(
        `${fixture.id.padEnd(48)} before: ${JSON.stringify(last?.lines?.[0]?.score ?? last?.terminal)}`,
      );
    }
  } finally {
    engine.terminate();
    await vite.close();
  }

  fs.writeFileSync(outPath, `${JSON.stringify(out, null, 1)}\n`);
  console.log(
    `Wrote ${Object.keys(out.lines).length} lines to ${path.relative(rootDir, outPath)} in ${((performance.now() - startedAt) / 1000).toFixed(1)} s`,
  );
}

main().catch((err) => {
  console.error('Recording review fixtures failed:', err);
  process.exit(1);
});
